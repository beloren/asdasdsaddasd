--------------------------------------------------------------------------------
-- OreIncome
-- ЕДИНАЯ формула пассивного дохода кристалла на подиуме. Раньше она была
-- размазана по четырём местам (PassiveIncomeService.incomePerMinute,
-- GeodeService.incomeFor, RockService — табличка над кристаллом в руках,
-- CollectionMenu на клиенте) и в каждом считалась чуть по-своему. Теперь
-- источник истины один, и сервер с клиентом физически не могут разойтись в
-- показаниях.
--
--------------------------------------------------------------------------------
-- РЕБАЛАНС v2 (по прямому запросу — "кристаллы должны давать мелкую
-- пассивку, а не решать экономику, главный заработок = шахтёрство").
--
-- Формула упрощена до одного понятного числа:
--   $/мин = PassiveIncomePercentOfCart × ПОЛНАЯ_тележка(тир игрока)
--           × (1 + (уровень-1) × IncomePerLevel) × мутация(≤IncomeMultiplierCap)
--           × PassiveIncomeMultiplier
--
-- "ПОЛНАЯ тележка" — Capacity(тир тележки) × CrystalValue(тир шахты), то
-- есть ровно "продай сейчас полную тележку своей текущей рудой". При
-- дефолтных 5% × 0.5 (см. Config.Geodes.PassiveIncomePercentOfCart и
-- .PassiveIncomeMultiplier) это ~2.5% от такой продажи В МИНУТУ — за час
-- голого стояния у подиума набегает даже без апгрейдов подиума меньше
-- полутора тележек, а не десятки, как раньше на топ-руде. Уровень руды
-- (дубликаты) даёт мелкую добавку (макс +36% на 10 уровне), а не решает
-- сам факт "выгодно/невыгодно" — сравнимо со старым поведением, просто на
-- порядок меньше по абсолютной силе.
--------------------------------------------------------------------------------
-- СТАРЫЙ КОММЕНТАРИЙ (оставлен для истории решения, см. выше — актуальную
-- формулу это уже не описывает, IncomePerMinute/CartShare руды больше не
-- читаются):
--------------------------------------------------------------------------------
-- БЫЛО: у каждой руды стояло одно фиксированное число IncomePerMinute, и
-- между соседними ТИРАМИ жеод оно прыгало примерно в 10 раз
-- (333 → 3 333 → 20 000 → 166 667 → ... → 7 000 000 000). Два следствия,
-- оба плохие:
--   1. Найти жеоду следующего тира = мгновенно умножить весь пассивный
--      доход на 10. Вся коллекция до этого момента обесценивалась разом,
--      промежуточные руды не имели смысла вообще.
--   2. Число не зависело от того, где игрок находится в прогрессии. Руда
--      топового тира, попавшая к новичку (её можно купить за Robux —
--      см. Config.DevProducts.GeodePacks), давала доход, несопоставимый
--      ни с чем в его игре, и ломала экономику досуха.
--
-- СТАЛО: доход складывается из ДВУХ частей.
--
--   income/сек = ( Flat[руда] + CartShare[руда] × половина_тележки ) ×
--                × уровень × мутации × глобальный_множитель
--
--   • Flat — небольшой абсолютный «пол» в $/сек. Растёт ПЛАВНО от 5/сек у
--     самой первой руды до 60/сек у последней (шаг ~+9% на руду, ~+29% на
--     тир жеоды вместо прежних +900%). Это тот самый «5 в секунду из первой
--     жеоды». Он специально маленький: его задача — чтобы у новичка вообще
--     капало что-то осмысленное, а не чтобы кормить лейт.
--
--   • CartShare × половина_тележки — ОСНОВНАЯ часть. «Половина тележки» —
--     это половина вместимости тележки игрока, умноженная на цену его
--     текущей руды (Config.CartTiers[тир].Capacity / 2 × CrystalValue тира
--     шахты). Проще говоря — сколько стоит наполовину забитая тележка
--     ПРЯМО СЕЙЧАС, у этого конкретного игрока.
--
-- ПОЧЕМУ ИМЕННО ПОЛОВИНА ТЕЛЕЖКИ. Это оказался почти идеальный измеритель
-- «сколько игрок зарабатывает активной игрой в секунду»: если посчитать
-- реальный доход рейса (полная тележка × комбо / время рейса), он идёт
-- почти вровень со стоимостью половины тележки на всех девяти тирах. То
-- есть привязка к нему автоматически держит пассивный доход в постоянной
-- пропорции к активному, на любой стадии игры, без ручной подгонки чисел
-- после каждого ребаланса цен. Раньше эту пропорцию приходилось
-- переписывать вручную и она всё равно разъезжалась.
--
-- ЧТО ЭТО ДАЁТ НА ПРАКТИКЕ (доля пассивного дохода от активного, у игрока
-- с рудой «своего» тира): T1 ~70%, T2 ~27%, T3 ~22%, T4-T9 стабильно
-- 12-16%. Разброс между худшей и лучшей рудой ВНУТРИ одного тира игрока —
-- ровно x10 на всей дистанции: коллекционировать по-прежнему выгодно, но
-- редкая руда больше не отменяет всю остальную игру.
--
-- ПОЧЕМУ ДОЛЯ У ПЕРВОЙ РУДЫ 2.5%, А НЕ 5%. Обсуждалось 5%. На бумаге это
-- звучит скромно, но у игрока на тире 1 активный доход всего ~10$/сек, и
-- 5% + флэт 5$/сек дают уже ~80% от всей его активной добычи — подиум
-- начинает конкурировать с самой игрой в первые же минуты. 2.5% оставляет
-- обещанные 5$/сек флэта главной частью награды на старте. Если хочется
-- ровно 5% — крути CartShare у Quartz в Config.Geodes.Ores, формулу это не
-- затрагивает.
--------------------------------------------------------------------------------

local ReplicatedStorage = game:GetService("ReplicatedStorage")
local Config = require(ReplicatedStorage.Shared.Config)
local CollectionKey = require(ReplicatedStorage.Shared.CollectionKey)

local OreIncome = {}

-- Ограничитель бонуса мутаций. Отдельная функция, чтобы и сервер, и клиент
-- применяли ОДИН потолок (Config.Mutations.IncomeMultiplierCap).
function OreIncome.MutationMultiplier(value)
	local multiplier = tonumber(value) or 1
	if multiplier <= 1 then return 1 end
	return math.min(multiplier, Config.Mutations.IncomeMultiplierCap or 1)
end

function OreIncome.LevelMultiplier(level)
	local numeric = tonumber(level) or 1
	if numeric < 1 then numeric = 1 end
	return 1 + (numeric - 1) * (Config.Geodes.IncomePerLevel or 0)
end

--------------------------------------------------------------------------------
-- СТОИМОСТЬ ПОЛОВИНЫ ТЕЛЕЖКИ.
-- Комбо-множитель тут НЕ учитывается намеренно: он зависит от того, как
-- игрок реально возит груз (см. Config.Cart.ComboThresholds), а нам нужна
-- стабильная опорная величина, а не награда за конкретный рейс. Комбо уже
-- учтён в том, что доля подобрана по РЕАЛЬНОМУ доходу рейса вместе с ним.
--
-- Оба тира клэмпятся по границам таблиц: атрибуты MineTier/CartTier
-- прилетают на клиент асинхронно и в первые кадры после захода могут быть
-- ещё nil — тогда честно считаем по тиру 1, а не падаем и не показываем
-- ноль.
--------------------------------------------------------------------------------
function OreIncome.HalfCartValue(mineTier, cartTier)
	return OreIncome.FullCartValue(mineTier, cartTier) * 0.5
end

-- ЭКОНОМИКА v3: стоимость полной тележки = СРЕДНИЙ дроп пещеры × вместимость
-- × максимальное комбо (Config.CartValue). Раньше здесь бралась цена самой
-- редкой руды окна (2% шанс) без комбо — отсюда и завышенные оценки.
function OreIncome.FullCartValue(mineTier, cartTier)
	return Config.CartValue(mineTier, cartTier)
end

--------------------------------------------------------------------------------
-- ГЛАВНАЯ ФУНКЦИЯ ПАССИВКИ (v3). key — ключ ячейки коллекции ("Quartz" или
-- "Quartz#Rusty"). Возвращает $/МИНУТУ.
--
-- Доход = CartShare кристалла × твой активный доход в минуту
-- (Config.IncomePerMinute) × уровень ячейки × мутация. CartShare у каждого
-- кристалла свой: Quartz 2.5% … Infinitum 25%, Titanheart ~29% — раньше
-- это поле не использовалось, и любой кристалл на подиуме давал одинаково.
-- Теперь редкий кристалл реально стоит того, чтобы за ним охотиться.
--------------------------------------------------------------------------------
-- v4 (P1): доход кристалла ФИКСИРОВАННЫЙ — BaseIncomePerMinute считается
-- в Config от родной пещеры кристалла (см. «ПАССИВКА P1» в Config.lua).
-- mineTier/cartTier оставлены в сигнатуре ради совместимости и не читаются.
function OreIncome.PerMinute(key, level, _mineTier, _cartTier)
	local ore = Config.Geodes.Ores[CollectionKey.BaseOre(key)]
	if not ore then return 0 end

	return (tonumber(ore.BaseIncomePerMinute) or 0)
		* OreIncome.LevelMultiplier(level)
		* OreIncome.MutationMultiplier(CollectionKey.Multiplier(key))
		* (tonumber(Config.Geodes.PassiveIncomeMultiplier) or 1)
end

-- Удобная обёртка для клиента: тиры берутся из атрибутов самого игрока
-- (их выставляют PlotService/CartService — см. SetAttribute("MineTier"/
-- "CartTier")), поэтому вызывающему коду не нужно их доставать самому.
function OreIncome.PerMinuteForPlayer(player, key, level)
	-- v8: перк Safe Income (PrestigeService публикует атрибут PerkBonus_Passive).
	local perk = player and tonumber(player:GetAttribute("PerkBonus_Passive")) or 0
	-- v4: геймпасс «2x Safe Income» (атрибут Owns_DoubleSafe ставит MonetizationService).
	local pass = (player and player:GetAttribute("Owns_DoubleSafe") == true)
		and (tonumber(Config.GamePasses.DoubleSafe and Config.GamePasses.DoubleSafe.Multiplier) or 2) or 1
	return OreIncome.PerMinute(key, level) * (1 + perk) * pass
end

return OreIncome
